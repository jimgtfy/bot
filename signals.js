// বর্তমান দিন অনুযায়ী সিগন্যাল পাওয়ার ফাংশন
function getTodaySignals() {
    const now = new Date();
    let day = now.getDate(); // বর্তমান তারিখ (১ থেকে ৩১)
    
    // যদি বর্তমান তারিখ ৩০ এর বেশি হয় (যেমন ৩১), তবে ৩০ দিন সাইকেল থেকে ডেটা দেখাবে বা ১ থেকে সাইকেল করবে
    if (day > 30) {
        day = ((day - 1) % 30) + 1;
    }
    
    // যদি নির্দিষ্ট দিনের ডেটা masterSignals-এ না থাকে, তবে দিন ১ এর ডেটা দেখাবে
    let signals = masterSignals[day] || masterSignals[1];
    
    // সময় অনুযায়ী ক্রমানুসারে সাজানো নিশ্চিত করা
    return signals.sort((a, b) => a.time.localeCompare(b.time));
}

